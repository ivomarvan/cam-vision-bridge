import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { describe, expect, it } from 'vitest';

import type {
  Box,
  CamVisionBridgeV1TextMessage,
  ErrorMessage,
  FrameHeader,
  Hello,
  Result,
  Text,
  Welcome,
} from './generated';

const execFileAsync = promisify(execFile);

const PROTOCOL_DIR = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = resolve(PROTOCOL_DIR, '../..');
const GENERATOR = join(WEB_ROOT, 'scripts/generate-protocol-types.mjs');
const COMMITTED = join(PROTOCOL_DIR, 'generated.ts');

/**
 * Run the generator into a temporary file and return the TypeScript it wrote.
 *
 * @returns Fresh source produced from the committed JSON Schema.
 */
async function generateFresh(): Promise<string> {
  const directory = await mkdtemp(join(tmpdir(), 'protocol-types-'));
  try {
    const outPath = join(directory, 'generated.ts');
    await execFileAsync(process.execPath, [GENERATOR, '--out', outPath], { cwd: WEB_ROOT });
    return await readFile(outPath, 'utf8');
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

/**
 * Slice one generated interface, from its export through the closing brace.
 *
 * @param source - Full generated TypeScript file.
 * @param name - Interface name declared in that file.
 * @returns The interface text, or an empty string when the name is absent.
 */
function interfaceBlock(source: string, name: string): string {
  const marker = `export interface ${name} {`;
  const start = source.indexOf(marker);
  if (start === -1) {
    return '';
  }
  const end = source.indexOf('\n}', start);
  if (end === -1) {
    return '';
  }
  return source.slice(start, end + 2);
}

describe('generated protocol types', () => {
  it('exports result and box from the schema', async () => {
    const source = await readFile(COMMITTED, 'utf8');
    expect(interfaceBlock(source, 'Result')).toContain('readonly t: \'result\';');
    expect(interfaceBlock(source, 'Box')).toContain('readonly t: \'box\';');
    const box = {
      t: 'box',
      x: 0,
      y: 0,
      w: 1,
      h: 1,
    } satisfies Box;
    const result = {
      v: 1,
      t: 'result',
      frame_id: 0,
      items: [box],
      processing_ms: 1,
    } satisfies Result;
    const message = result satisfies CamVisionBridgeV1TextMessage;
    expect(message.t).toBe('result');
    expect(message.items[0]).toBe(box);
  });

  it('allows text without coordinates', async () => {
    const source = await readFile(COMMITTED, 'utf8');
    const textBlock = interfaceBlock(source, 'Text');
    expect(textBlock).toContain('readonly x?:');
    expect(textBlock).toContain('readonly y?:');
    const panel: Text = { t: 'text', text: 'fps' };
    const placed: Text = { t: 'text', text: 'label', x: 0.2, y: 0.4 };
    expect(panel.x).toBeUndefined();
    expect(placed.x).toBe(0.2);
    expect(placed.y).toBe(0.4);
  });

  it('covers hello, welcome, error, and frame', () => {
    const hello = {
      v: 1,
      t: 'hello',
      device_ua: 'test',
      width: 640,
      height: 480,
    } satisfies Hello;
    const welcome = { v: 1, t: 'welcome' } satisfies Welcome;
    const failure = { v: 1, t: 'error', reason: 'dropped' } satisfies ErrorMessage;
    const frame = {
      v: 1,
      t: 'frame',
      frame_id: 0,
      captured_at: '2026-11-22T00:00:00.000Z',
      w: 1,
      h: 1,
      part: 0,
      parts: 1,
      total_bytes: 1,
    } satisfies FrameHeader;
    expect([hello.t, welcome.t, failure.t, frame.t]).toEqual([
      'hello',
      'welcome',
      'error',
      'frame',
    ]);
  });
});

describe('generate:protocol drift', () => {
  it('matches a fresh generator run', async () => {
    const committed = await readFile(COMMITTED, 'utf8');
    const fresh = await generateFresh();
    expect(committed).toContain('Do not edit this file by hand.');
    expect(fresh).toBe(committed);
  });

  it('fails when a copy of generated.ts gains a line', async () => {
    const directory = await mkdtemp(join(tmpdir(), 'protocol-types-copy-'));
    try {
      const committed = await readFile(COMMITTED, 'utf8');
      const copyPath = join(directory, 'generated.copy.ts');
      await writeFile(copyPath, `${committed}\n// hand edit\n`);
      const copy = await readFile(copyPath, 'utf8');
      const fresh = await generateFresh();
      expect(copy).not.toBe(fresh);
      expect(committed).toBe(fresh);
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });
});
