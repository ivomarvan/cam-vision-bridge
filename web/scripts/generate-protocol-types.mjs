// @ts-check
/**
 * Generate TypeScript types for protocol v1 from the committed JSON Schema.
 *
 * Schema path is `../../schema/cam-vision-bridge-v1.schema.json` relative to this
 * file: the repository layout on the host, and `/schema/...` when `web/scripts`
 * is mounted at `/app/scripts` and compose mounts `./schema` at `/schema`.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const DEFAULT_SCHEMA = resolve(SCRIPT_DIR, '../../schema/cam-vision-bridge-v1.schema.json');
const DEFAULT_OUT = resolve(SCRIPT_DIR, '../src/protocol/generated.ts');

const HEADER = [
  '/**',
  ' * Generated from schema/cam-vision-bridge-v1.schema.json.',
  ' * Do not edit this file by hand.',
  ' * Regenerate with: npm run generate:protocol',
  ' */',
].join('\n');

/** Annotations that do not change the TypeScript shape. Numeric bounds stay comments-free: TypeScript has no range types. */
const ANNOTATIONS = [
  '$comment',
  'default',
  'description',
  'examples',
  'exclusiveMaximum',
  'exclusiveMinimum',
  'format',
  'maxLength',
  'maximum',
  'minLength',
  'minimum',
  'pattern',
  'title',
];

/**
 * Failure while turning the protocol schema into TypeScript.
 */
class SchemaCompileError extends Error {
  /**
   * @param {string} message - What the schema contained that this generator cannot encode.
   */
  constructor(message) {
    super(message);
    this.name = 'SchemaCompileError';
  }
}

/**
 * @typedef {Record<string, unknown>} JsonObject
 */

/**
 * @param {unknown} value
 * @returns {value is JsonObject}
 */
function isJsonObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * @param {JsonObject} schema
 * @param {readonly string[]} allowed
 * @param {string} path
 * @returns {void}
 */
function assertOnlyKeys(schema, allowed, path) {
  const allowedSet = new Set(allowed);
  for (const key of Object.keys(schema)) {
    if (!allowedSet.has(key)) {
      throw new SchemaCompileError(`Unsupported keyword ${key} at ${path}`);
    }
  }
}

/**
 * @param {string} name
 * @param {string} path
 * @returns {void}
 */
function assertIdent(name, path) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
    throw new SchemaCompileError(`Invalid identifier ${name} at ${path}`);
  }
}

/**
 * @param {JsonObject} schema
 * @param {string} key
 * @returns {unknown}
 */
function requiredField(schema, key) {
  if (!Object.hasOwn(schema, key)) {
    throw new SchemaCompileError(`Missing ${key}`);
  }
  return schema[key];
}

/**
 * @param {JsonObject} schema
 * @param {string} key
 * @returns {string | undefined}
 */
function optionalString(schema, key) {
  if (!Object.hasOwn(schema, key)) {
    return undefined;
  }
  const value = schema[key];
  if (typeof value !== 'string') {
    throw new SchemaCompileError(`Expected string at ${key}`);
  }
  return value;
}

/**
 * @param {JsonObject} schema
 * @param {string} key
 * @returns {number | undefined}
 */
function optionalNumber(schema, key) {
  if (!Object.hasOwn(schema, key)) {
    return undefined;
  }
  const value = schema[key];
  if (typeof value !== 'number') {
    throw new SchemaCompileError(`Expected number at ${key}`);
  }
  return value;
}

/**
 * @param {string | undefined} description
 * @returns {string}
 */
function renderDoc(description) {
  if (description === undefined || description.length === 0) {
    return '';
  }
  const safe = description.replaceAll('*/', '*\\/');
  const lines = safe.split('\n').map((line) => ` * ${line}`.trimEnd());
  return `/**\n${lines.join('\n')}\n */\n`;
}

/**
 * @param {unknown} value
 * @param {string} path
 * @returns {string}
 */
function renderLiteral(value, path) {
  if (typeof value === 'string') {
    return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }
  throw new SchemaCompileError(`Unsupported literal at ${path}`);
}

/**
 * @param {string} ref
 * @param {string} path
 * @returns {string}
 */
function refToName(ref, path) {
  const prefix = '#/$defs/';
  if (!ref.startsWith(prefix)) {
    throw new SchemaCompileError(`Unsupported $ref ${ref} at ${path}`);
  }
  const name = ref.slice(prefix.length);
  assertIdent(name, path);
  return name;
}

/**
 * @param {string} typeText
 * @returns {string}
 */
function parenthesize(typeText) {
  if (/[|&[\]]/.test(typeText)) {
    return `(${typeText})`;
  }
  return typeText;
}

/**
 * @param {string} itemType
 * @returns {string}
 */
function asReadonlyArray(itemType) {
  return `readonly ${parenthesize(itemType)}[]`;
}

/**
 * @param {unknown} value
 * @param {string} path
 * @returns {string}
 */
function renderEnum(value, path) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new SchemaCompileError(`Expected non-empty enum at ${path}`);
  }
  return value.map((item) => renderLiteral(item, path)).join(' | ');
}

/**
 * @param {unknown} value
 * @param {string} path
 * @param {string} keyword
 * @returns {string}
 */
function renderUnion(value, path, keyword) {
  if (!Array.isArray(value)) {
    throw new SchemaCompileError(`Expected array at ${path}.${keyword}`);
  }
  const parts = value.map((part, index) => renderType(part, `${path}.${keyword}[${index}]`));
  return parts.join(' | ');
}

/**
 * @param {unknown} prefix
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {string}
 */
function renderPrefixTuple(prefix, schema, path) {
  if (!Array.isArray(prefix) || prefix.length === 0) {
    throw new SchemaCompileError(`Expected prefixItems at ${path}`);
  }
  const parts = prefix.map((part, index) => renderType(part, `${path}.prefixItems[${index}]`));
  const min = optionalNumber(schema, 'minItems');
  const max = optionalNumber(schema, 'maxItems');
  if (min !== parts.length || max !== parts.length) {
    throw new SchemaCompileError(`prefixItems bounds must be fixed at ${path}`);
  }
  return `readonly [${parts.join(', ')}]`;
}

/**
 * @param {string} itemType
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {string}
 */
function renderItemArray(itemType, schema, path) {
  const min = optionalNumber(schema, 'minItems') ?? 0;
  const max = optionalNumber(schema, 'maxItems');
  if (max === undefined && min === 0) {
    return asReadonlyArray(itemType);
  }
  if (max === undefined && min > 0) {
    const head = Array.from({ length: min }, () => itemType);
    return `readonly [${head.join(', ')}, ...${parenthesize(itemType)}[]]`;
  }
  if (max === min) {
    const members = Array.from({ length: min }, () => itemType);
    return `readonly [${members.join(', ')}]`;
  }
  throw new SchemaCompileError(`Unsupported array bounds at ${path}`);
}

/**
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {string}
 */
function renderArray(schema, path) {
  assertOnlyKeys(
    schema,
    ['items', 'maxItems', 'minItems', 'prefixItems', 'type', ...ANNOTATIONS],
    path,
  );
  const prefix = Object.hasOwn(schema, 'prefixItems') ? schema.prefixItems : undefined;
  if (prefix !== undefined) {
    return renderPrefixTuple(prefix, schema, path);
  }
  return renderItemArray(renderType(requiredField(schema, 'items'), `${path}.items`), schema, path);
}

/**
 * @param {string} typeName
 * @returns {string | undefined}
 */
function primitiveType(typeName) {
  if (typeName === 'string' || typeName === 'boolean' || typeName === 'null') {
    return typeName === 'null' ? 'null' : typeName;
  }
  if (typeName === 'number' || typeName === 'integer') {
    return 'number';
  }
  return undefined;
}

/**
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {string | undefined}
 */
function renderKeywordType(schema, path) {
  const ref = optionalString(schema, '$ref');
  if (ref !== undefined) {
    assertOnlyKeys(schema, ['$ref', ...ANNOTATIONS], path);
    return refToName(ref, path);
  }
  if (Object.hasOwn(schema, 'const')) {
    assertOnlyKeys(schema, ['const', 'type', ...ANNOTATIONS], path);
    return renderLiteral(schema.const, path);
  }
  if (Object.hasOwn(schema, 'enum')) {
    assertOnlyKeys(schema, ['enum', 'type', ...ANNOTATIONS], path);
    return renderEnum(schema.enum, path);
  }
  if (Object.hasOwn(schema, 'anyOf')) {
    assertOnlyKeys(schema, ['anyOf', ...ANNOTATIONS], path);
    return renderUnion(schema.anyOf, path, 'anyOf');
  }
  if (Object.hasOwn(schema, 'oneOf')) {
    assertOnlyKeys(schema, ['discriminator', 'oneOf', ...ANNOTATIONS], path);
    return renderUnion(schema.oneOf, path, 'oneOf');
  }
  return undefined;
}

/**
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {string}
 */
function renderPrimitive(schema, path) {
  const typeName = schema.type;
  if (typeof typeName !== 'string') {
    throw new SchemaCompileError(`Unsupported schema at ${path}`);
  }
  assertOnlyKeys(schema, ['type', ...ANNOTATIONS], path);
  const primitive = primitiveType(typeName);
  if (primitive === undefined) {
    throw new SchemaCompileError(`Unsupported type ${typeName} at ${path}`);
  }
  return primitive;
}

/**
 * @param {unknown} schema
 * @param {string} path
 * @returns {string}
 */
function renderType(schema, path) {
  if (!isJsonObject(schema)) {
    throw new SchemaCompileError(`Expected schema object at ${path}`);
  }
  const keywordType = renderKeywordType(schema, path);
  if (keywordType !== undefined) {
    return keywordType;
  }
  if (schema.type === 'array') {
    return renderArray(schema, path);
  }
  return renderPrimitive(schema, path);
}

/**
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {Set<string>}
 */
function requiredSet(schema, path) {
  if (!Object.hasOwn(schema, 'required')) {
    return new Set();
  }
  const value = schema.required;
  if (!Array.isArray(value) || !value.every((item) => typeof item === 'string')) {
    throw new SchemaCompileError(`Expected required string array at ${path}`);
  }
  return new Set(value);
}

/**
 * @param {JsonObject} schema
 * @param {string} path
 * @returns {string}
 */
function renderObjectBody(schema, path) {
  assertOnlyKeys(
    schema,
    ['additionalProperties', 'properties', 'required', 'type', ...ANNOTATIONS],
    path,
  );
  if (schema.type !== 'object') {
    throw new SchemaCompileError(`Expected object type at ${path}`);
  }
  if (schema.additionalProperties !== false) {
    throw new SchemaCompileError(`additionalProperties must be false at ${path}`);
  }
  const properties = requiredField(schema, 'properties');
  if (!isJsonObject(properties)) {
    throw new SchemaCompileError(`Expected properties object at ${path}`);
  }
  const required = requiredSet(schema, path);
  const lines = [];
  for (const [prop, propSchema] of Object.entries(properties)) {
    assertIdent(prop, `${path}.${prop}`);
    const mark = required.has(prop) ? '' : '?';
    const typeText = renderType(propSchema, `${path}.${prop}`);
    lines.push(`  readonly ${prop}${mark}: ${typeText};`);
  }
  if (lines.length === 0) {
    throw new SchemaCompileError(`Empty object at ${path}`);
  }
  return lines.join('\n');
}

/**
 * @param {string} name
 * @param {unknown} definition
 * @returns {string}
 */
function renderNamedDefinition(name, definition) {
  if (!isJsonObject(definition)) {
    throw new SchemaCompileError(`$defs.${name} must be an object`);
  }
  const title = optionalString(definition, 'title');
  if (title !== undefined && title !== name) {
    throw new SchemaCompileError(`$defs.${name} title ${title} does not match the key`);
  }
  assertIdent(name, `$defs.${name}`);
  const body = renderObjectBody(definition, `$defs.${name}`);
  return `${renderDoc(optionalString(definition, 'description'))}export interface ${name} {\n${body}\n}`;
}

/**
 * @param {JsonObject} schema
 * @returns {string}
 */
function renderRoot(schema) {
  assertOnlyKeys(
    schema,
    ['$defs', '$id', '$schema', 'description', 'discriminator', 'oneOf', 'title'],
    'root',
  );
  const title = optionalString(schema, 'title');
  if (title === undefined) {
    throw new SchemaCompileError('Root schema is missing title');
  }
  assertIdent(title, 'root.title');
  const oneOf = requiredField(schema, 'oneOf');
  if (!Array.isArray(oneOf)) {
    throw new SchemaCompileError('Root oneOf must be an array');
  }
  const members = oneOf.map((part, index) => `  | ${renderType(part, `root.oneOf[${index}]`)}`);
  const doc = renderDoc(optionalString(schema, 'description'));
  return `${doc}export type ${title} =\n${members.join('\n')};`;
}

/**
 * Render protocol TypeScript from a JSON Schema document.
 *
 * @param {unknown} schema - Draft 2020-12 document produced from the Python models.
 * @returns {string} TypeScript source. Write it unchanged.
 * @throws {SchemaCompileError} When the schema uses a construct this generator does not encode.
 */
export function renderProtocolTypes(schema) {
  if (!isJsonObject(schema)) {
    throw new SchemaCompileError('Schema root must be an object');
  }
  const defs = requiredField(schema, '$defs');
  if (!isJsonObject(defs)) {
    throw new SchemaCompileError('Schema is missing $defs');
  }
  const blocks = [HEADER];
  for (const [name, definition] of Object.entries(defs)) {
    blocks.push(renderNamedDefinition(name, definition));
  }
  blocks.push(renderRoot(schema));
  return `${blocks.join('\n\n')}\n`;
}

/**
 * @param {string} schemaPath
 * @param {string} outPath
 * @returns {Promise<void>}
 */
async function writeGenerated(schemaPath, outPath) {
  const parsed = /** @type {unknown} */ (JSON.parse(await readFile(schemaPath, 'utf8')));
  const rendered = renderProtocolTypes(parsed);
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, rendered, 'utf8');
}

/**
 * @returns {Promise<void>}
 */
async function main() {
  const { values } = parseArgs({
    options: {
      out: { type: 'string', default: DEFAULT_OUT },
      schema: { type: 'string', default: DEFAULT_SCHEMA },
    },
  });
  const schemaPath = values.schema;
  const outPath = values.out;
  if (schemaPath === undefined || outPath === undefined) {
    throw new SchemaCompileError('Missing --schema or --out');
  }
  await writeGenerated(schemaPath, outPath);
}

const invokedPath = process.argv[1];
if (
  invokedPath !== undefined &&
  import.meta.url === pathToFileURL(resolve(invokedPath)).href
) {
  main().catch((error) => {
    const message = error instanceof Error ? error.message : 'Unknown generator failure';
    process.stderr.write(`generate-protocol-types: ${message}\n`);
    process.exitCode = 1;
  });
}
